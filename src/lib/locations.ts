// مقایسه‌ی مقاوم نام شهر/استان: فاصله‌های اضافه و نویسه‌های عربی/فارسی مشابه
// (ي/ی، ك/ک) و نیم‌فاصله را یکسان می‌کند تا آگهی‌های قدیمی با املای کمی متفاوت
// هم در فیلترها جا نیفتند.
export function normalizePlaceName(s: string | null | undefined): string {
  return (s || "")
    .trim()
    .replace(/ي/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/[\u200c\u200f\u200e]/g, " ")
    .replace(/\s+/g, " ")
    .toLowerCase();
}

export function placeNamesMatch(a: string | null | undefined, b: string | null | undefined): boolean {
  return normalizePlaceName(a) === normalizePlaceName(b);
}

// نسخه‌ی فشرده (بدون فاصله/نیم‌فاصله) برای جست‌وجوی متنی داخل آدرس
function compactPlaceName(s: string | null | undefined): string {
  return normalizePlaceName(s).replace(/[\s\-_,،.]/g, "");
}

/** استانِ یک شهر را از فهرست داخلی پیدا می‌کند. */
export function findProvinceOfCity(city: string | null | undefined): string {
  const target = normalizePlaceName(city);
  if (!target) return "";
  for (const p of PROVINCES) {
    if (p.cities.some((c) => normalizePlaceName(c) === target)) return p.name;
  }
  return "";
}

/** محله‌های یک شهر، با مقایسه‌ی مقاوم نام شهر. */
export function getNeighborhoodsLoose(city: string | null | undefined): string[] {
  const target = normalizePlaceName(city);
  if (!target) return [];
  for (const key of Object.keys(NEIGHBORHOODS)) {
    if (normalizePlaceName(key) === target) return NEIGHBORHOODS[key];
  }
  return [];
}

/** انتخاب شهر کاربر (همان ساختاری که در CityGate ذخیره می‌شود). */
export type CityPreference = { mode: "all" | "city"; province?: string; city?: string } | null | undefined;

type ListingLocation = {
  city?: string | null;
  province?: string | null;
  neighborhood?: string | null;
  address?: string | null;
  title?: string | null;
};

/**
 * آیا این آگهی مربوط به شهرِ انتخاب‌شده‌ی کاربر است؟
 *
 * نکته‌ی مهم: بسیاری از آگهی‌های قدیمی ستون «شهر» را خالی دارند (قبل از
 * افزودن آن ستون ثبت شده‌اند). اگر فقط شهر آگهی را مقایسه کنیم، صفحه‌ی
 * «شهر من» برای کاربر خالی می‌ماند. بنابراین به ترتیب:
 *   ۱) اگر شهر آگهی مشخص است → مقایسه‌ی دقیق شهر
 *   ۲) اگر خالی است ولی استان با استان شهر انتخابی یکی است → همان شهر فرض می‌شود
 *   ۳) در آخر، نام شهر/محله‌های شناخته‌شده در آدرس، محله و عنوان جست‌وجو می‌شود
 */
export function listingMatchesCity(listing: ListingLocation, pref: CityPreference): boolean {
  if (!pref || pref.mode !== "city" || !pref.city) return true;
  const wantedCity = normalizePlaceName(pref.city);
  const wantedProvince = normalizePlaceName(pref.province || findProvinceOfCity(pref.city));

  // ۱) شهر آگهی ثبت شده است
  if (listing.city) return normalizePlaceName(listing.city) === wantedCity;

  // ۲) شهر آگهی خالی است — اگر استانش با شهر انتخابی یکی باشد، متعلق به همان شهر است
  if (listing.province && wantedProvince && normalizePlaceName(listing.province) === wantedProvince) return true;

  // ۳) جست‌وجوی متنی در محله/آدرس/عنوان
  const haystack = compactPlaceName([listing.neighborhood, listing.address, listing.title].filter(Boolean).join(" "));
  if (!haystack) return false;
  if (wantedCity.length >= 3 && haystack.includes(compactPlaceName(pref.city))) return true;
  return [pref.city, ...getNeighborhoodsLoose(pref.city)].some((m) => {
    const marker = compactPlaceName(m);
    return marker.length >= 4 && haystack.includes(marker);
  });
}

/** آگهی‌های مربوط به شهرِ انتخابی کاربر (اگر «کل کشور» باشد، همه برمی‌گردند). */
export function filterByCity<T extends ListingLocation>(items: T[], pref: CityPreference): T[] {
  if (!pref || pref.mode !== "city" || !pref.city) return items;
  return items.filter((l) => listingMatchesCity(l, pref));
}
